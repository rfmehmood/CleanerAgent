class ScanWorkerThread(QThread):
    progress_updated = Signal(str, int, str)
    scan_finished = Signal(list, float)

    def __init__(self, selected_categories: List[str], exclusions: List[str]):
        super().__init__()
        self.selected_categories = selected_categories
        self.exclusions = exclusions
        self.engine = ScannerEngine(exclusions=exclusions)
        self.dup_finder = DuplicateFinder()
        self.is_running = True

    def run(self):
        start_time = time.time()
        candidates = []

        def on_progress(name: str, count: int, cat: str):
            if self.is_running:
                self.progress_updated.emit(name, count, cat)

        normal_categories = [c for c in self.selected_categories if c != ScanCategory.DUPLICATES]
        if normal_categories:
            found = self.engine.scan_categories(normal_categories, progress_callback=on_progress)
            candidates.extend(found)

        if ScanCategory.DUPLICATES in self.selected_categories and self.is_running:
            self.progress_updated.emit("Cataloging potential duplicates...", len(candidates), ScanCategory.DUPLICATES)
            import os
            home = os.path.expanduser("~")
            scan_dirs = [os.path.join(home, "Downloads"), os.path.join(home, "Desktop")]
            dup_groups = self.dup_finder.find_duplicates(
                scan_dirs,
                progress_callback=lambda msg, count: self.progress_updated.emit(msg, len(candidates) + count, ScanCategory.DUPLICATES)
            )
            for g in dup_groups:
                candidates.extend(g["duplicates"])

        duration = time.time() - start_time
        self.scan_finished.emit(candidates, duration)

    def cancel(self):
        self.is_running = False
        self.engine.cancel()
        self.dup_finder.cancel()

