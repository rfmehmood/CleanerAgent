class DeepScannerView(QWidget):
    scan_completed = Signal(list)

    def __init__(self, db_manager, settings_manager, parent=None):
        super().__init__(parent)
        self.db = db_manager
        self.settings = settings_manager
        self.worker: ScanWorkerThread = None
        self.elapsed_timer = QTimer(self)
        self.elapsed_timer.timeout.connect(self._update_elapsed_time)
        self.start_timestamp = 0
        self._init_ui()

    def _init_ui(self):
        main_layout = QVBoxLayout(self)
        main_layout.setContentsMargins(28, 28, 28, 28)
        main_layout.setSpacing(18)

        # Header Title
        top_box = QVBoxLayout()
        top_box.setSpacing(4)
        title = QLabel("Deep Storage Scanner")
        title.setProperty("class", "heading-1")
        sub = QLabel("Select categories to inspect. Scanning is strictly read-only and never deletes anything automatically.")
        sub.setProperty("class", "subtext")
        top_box.addWidget(title)
        top_box.addWidget(sub)
        main_layout.addLayout(top_box)

        # Selection Control Row
        sel_row = QHBoxLayout()
        sel_all_btn = QPushButton("✓ Select All")
        sel_all_btn.setProperty("class", "secondary-btn")
        sel_all_btn.clicked.connect(self._select_all_categories)
        desel_btn = QPushButton("✕ Deselect All")
        desel_btn.setProperty("class", "secondary-btn")
        desel_btn.clicked.connect(self._deselect_all_categories)
        sel_row.addWidget(sel_all_btn)
        sel_row.addWidget(desel_btn)
        sel_row.addStretch()
        main_layout.addLayout(sel_row)

        # Scrollable Category Groups
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QFrame.NoFrame)
        content_w = QWidget()
        content_layout = QVBoxLayout(content_w)
        content_layout.setSpacing(16)
        content_layout.setContentsMargins(0, 0, 0, 0)

        self.checkboxes: Dict[str, QCheckBox] = {}

        # Group 1: System & Web Caches
        g1_card = self._create_category_group(
            "🌐 System & Browser Caches",
            [ScanCategory.TEMP_FILES, ScanCategory.APP_CACHE, ScanCategory.BROWSER_CACHE, ScanCategory.LOGS_CRASH, ScanCategory.RECYCLE_BIN]
        )
        content_layout.addWidget(g1_card)

        # Group 2: Developer & AI Storage
        g2_card = self._create_category_group(
            "💻 Developer & Local AI Environments",
            [ScanCategory.PYTHON_CONDA, ScanCategory.NODE_JS, ScanCategory.AI_MODELS, ScanCategory.BUILD_ARTIFACTS]
        )
        content_layout.addWidget(g2_card)

        # Group 3: Deep Heuristics & Files
        g3_card = self._create_category_group(
            "🔍 Deep Analysis & Disk Hogs",
            [ScanCategory.LEFTOVERS, ScanCategory.LARGE_FILES, ScanCategory.DUPLICATES]
        )
        content_layout.addWidget(g3_card)

        scroll.setWidget(content_w)
        main_layout.addWidget(scroll, stretch=1)

        # Progress & Status Card
        self.progress_card = QFrame()
        self.progress_card.setProperty("class", "card")
        self.progress_card.setStyleSheet("background-color: #131c2e; border: 1px solid #1e293b; border-radius: 12px; padding: 16px;")
        p_layout = QVBoxLayout(self.progress_card)
        p_layout.setSpacing(8)

        status_row = QHBoxLayout()
        self.status_label = QLabel("Scanner Ready. Select categories and click Start Scan.")
        self.status_label.setProperty("class", "heading-3")
        self.time_label = QLabel("Elapsed: 00:00")
        self.time_label.setStyleSheet("color: #38bdf8; font-weight: 700; font-size: 13px;")
        status_row.addWidget(self.status_label)
        status_row.addStretch()
        status_row.addWidget(self.time_label)
        p_layout.addLayout(status_row)

        self.current_item_label = QLabel("")
        self.current_item_label.setStyleSheet("color: #94a3b8; font-size: 12.5px; font-family: monospace;")
        p_layout.addWidget(self.current_item_label)

        self.progress_bar = QProgressBar()
        self.progress_bar.setRange(0, 0)
        self.progress_bar.setVisible(False)
        p_layout.addWidget(self.progress_bar)

        main_layout.addWidget(self.progress_card)

        # Bottom Action Bar
        btn_layout = QHBoxLayout()
        self.start_btn = QPushButton("🚀 Start Full Scan")
        self.start_btn.setProperty("class", "action-blue-btn")
        self.start_btn.setStyleSheet("font-size: 14px; padding: 13px 32px;")
        self.start_btn.clicked.connect(self.start_scan)

        self.cancel_btn = QPushButton("✕ Cancel Scan")
        self.cancel_btn.setProperty("class", "danger-btn")
        self.cancel_btn.setStyleSheet("font-size: 14px; padding: 13px 24px;")
        self.cancel_btn.setEnabled(False)
        self.cancel_btn.clicked.connect(self.cancel_scan)

        btn_layout.addWidget(self.start_btn)
        btn_layout.addWidget(self.cancel_btn)
        btn_layout.addStretch()
        main_layout.addLayout(btn_layout)

    def _create_category_group(self, group_title: str, categories: List[str]) -> QFrame:
        card = QFrame()
        card.setProperty("class", "card")
        layout = QVBoxLayout(card)
        layout.setSpacing(12)

        g_title = QLabel(group_title)
        g_title.setProperty("class", "heading-3")
        g_title.setStyleSheet("color: #38bdf8; font-size: 15px; font-weight: 700;")
        layout.addWidget(g_title)

        grid = QGridLayout()
        grid.setSpacing(12)

        for i, cat in enumerate(categories):
            item_box = QVBoxLayout()
            item_box.setSpacing(2)

            cb = QCheckBox(cat)
            cb.setChecked(cat != ScanCategory.DUPLICATES) # duplicate off by default
            self.checkboxes[cat] = cb
            item_box.addWidget(cb)

            desc_text = CATEGORY_INFO.get(cat, ("", ""))[1]
            desc_lbl = QLabel(desc_text)
            desc_lbl.setStyleSheet("color: #94a3b8; font-size: 12px; padding-left: 30px;")
            desc_lbl.setWordWrap(True)
            item_box.addWidget(desc_lbl)

            grid.addLayout(item_box, i // 2, i % 2)

        layout.addLayout(grid)
        return card

    def _select_all_categories(self):
        for cb in self.checkboxes.values():
            cb.setChecked(True)

    def _deselect_all_categories(self):
        for cb in self.checkboxes.values():
            cb.setChecked(False)

    def start_scan(self):
        selected = [cat for cat, cb in self.checkboxes.items() if cb.isChecked()]
        if not selected:
            self.status_label.setText("⚠ Please select at least one category to scan.")
            return

        self.start_btn.setEnabled(False)
        self.cancel_btn.setEnabled(True)
        self.progress_bar.setVisible(True)
        self.status_label.setText("Scanning in progress...")
        self.start_timestamp = time.time()
        self.elapsed_timer.start(500)

        exclusions = self.settings.get_exclusions()
        self.worker = ScanWorkerThread(selected, exclusions)
        self.worker.progress_updated.connect(self._on_progress_update)
        self.worker.scan_finished.connect(self._on_scan_finished)
        self.worker.start()

    def cancel_scan(self):
        if self.worker:
            self.worker.cancel()
            self.status_label.setText("Cancelling scan, finishing current directory...")
            self.cancel_btn.setEnabled(False)

    def _update_elapsed_time(self):
        if self.start_timestamp > 0:
            elapsed = int(time.time() - self.start_timestamp)
            mins = elapsed // 60
            secs = elapsed % 60
            self.time_label.setText(f"Elapsed: {mins:02d}:{secs:02d}")

    def _on_progress_update(self, item_name: str, count: int, category: str):
        self.status_label.setText(f"Scanning {category} — Found {count} candidates")
        self.current_item_label.setText(f"Inspecting: {item_name[:90]}")

    def _on_scan_finished(self, candidates: list, duration: float):
        self.elapsed_timer.stop()
        self.start_btn.setEnabled(True)
        self.cancel_btn.setEnabled(False)
        self.progress_bar.setVisible(False)

        total_bytes = sum(c.get("size", 0) for c in candidates)
        tot_mb = total_bytes / (1024*1024)

        self.status_label.setText(f"✓ Scan Completed: Discovered {len(candidates)} candidates ({tot_mb:.1f} MB) in {duration:.1f}s")
        self.current_item_label.setText("Review candidates in Cleanup Center before taking any action.")

        cat_summary = {}
        for c in candidates:
            cat = c.get("category", "General")
            cat_summary[cat] = cat_summary.get(cat, 0) + 1

        self.db.record_scan(
            scan_type="Deep Scan",
            total_items=len(candidates),
            total_bytes=total_bytes,
            categories_summary=cat_summary,
            duration=duration
        )

        self.scan_completed.emit(candidates)
