from pathlib import Path
from typing import Dict, Any, Tuple
from ..cleanup.safety import SafetyPolicy
from ..scanner.categories import ScanCategory

class FileClassifier:
    """
    Deterministic rule-based classification engine.
    Analyzes item metadata to determine:
    - Target Category
    - Associated Application (if known)
    - Qualitative Confidence (High / Medium / Low)
    - Deletion Safety Tier (SAFE / CAUTION / RISKY / PROTECTED)
    - Human-readable Explanation & Potential Consequences
    - Recommended Action
    """

    KNOWN_CACHE_PATTERNS = {
        "pip": ("pip", ScanCategory.PYTHON_CONDA, "Pip package download cache", "Packages can be redownloaded automatically if needed", "High"),
        "npm": ("Node.js / npm", ScanCategory.NODE_JS, "NPM global cache", "Packages will be redownloaded upon install", "High"),
        "pnpm": ("pnpm", ScanCategory.NODE_JS, "pnpm content-addressable store cache", "Can be regenerated via pnpm install", "High"),
        "yarn": ("Yarn", ScanCategory.NODE_JS, "Yarn package cache", "Cached tarballs, safe to clear", "High"),
        "conda": ("Conda", ScanCategory.PYTHON_CONDA, "Conda package tarballs and index cache", "Can be regenerated with conda clean", "High"),
        "huggingface": ("Hugging Face", ScanCategory.AI_MODELS, "Hugging Face model weights and hub cache", "Models will need redownloading if used again", "Medium"),
        "ollama": ("Ollama", ScanCategory.AI_MODELS, "Ollama local model blobs", "Stored LLM weights; prefer using 'ollama rm' if active", "Medium"),
        "crashpad": ("Crashpad", ScanCategory.LOGS_CRASH, "Application crash telemetry dump", "Only useful for debugging past application crashes", "High"),
        "webcache": ("Web Browser", ScanCategory.BROWSER_CACHE, "HTTP web cache files", "Browser may load visited sites slightly slower initially", "High"),
        "code cache": ("Chromium/Electron", ScanCategory.APP_CACHE, "Compiled V8 bytecode cache", "Automatically regenerated by Chromium/Electron apps", "High"),
        "gpu_cache": ("GPU Shader", ScanCategory.APP_CACHE, "Compiled GPU shader cache", "Regenerated dynamically by GPU driver or application", "High"),
    }

    @classmethod
    def classify(cls, path_str: str, is_dir: bool, size_bytes: int, mtime: float) -> Dict[str, Any]:
        """
        Classifies an item deterministically based on location, name, type, and age.
        """
        try:
            p = Path(path_str).resolve()
        except Exception:
            return cls._fallback_classification(path_str, size_bytes)

        # Check safety policy first
        is_prot, prot_reason = SafetyPolicy.is_protected(str(p))
        if is_prot:
            return {
                "path": str(p),
                "is_dir": is_dir,
                "size": size_bytes,
                "category": "Protected System",
                "app_name": "System/Protected",
                "confidence": "High",
                "safety_tier": "PROTECTED",
                "explanation": f"Protected by safety policy: {prot_reason}",
                "consequences": "Attempting deletion could damage system stability or personal files.",
                "recommendation": "Do not delete.",
                "quarantine_available": False,
            }

        path_lower = str(p).lower()
        parts = [part.lower() for part in p.parts]
        name_lower = p.name.lower()

        # 1. Python / Conda caches
        if "pip\\cache" in path_lower or ".conda\\pkgs" in path_lower or "__pycache__" in parts or name_lower.endswith(".pyc"):
            return {
                "path": str(p),
                "is_dir": is_dir,
                "size": size_bytes,
                "category": ScanCategory.PYTHON_CONDA,
                "app_name": "Python / Conda",
                "confidence": "High",
                "safety_tier": "SAFE",
                "explanation": "Downloaded Python package wheel cache or compiled bytecode.",
                "consequences": "Packages can be automatically re-downloaded or re-compiled when needed.",
                "recommendation": "Safe to clear package caches.",
                "quarantine_available": True,
            }

        # 2. Node.js caches & node_modules
        if "node_modules" in parts:
            return {
                "path": str(p),
                "is_dir": is_dir,
                "size": size_bytes,
                "category": ScanCategory.NODE_JS,
                "app_name": "Node.js Project Dependencies",
                "confidence": "High",
                "safety_tier": "RISKY",
                "explanation": "Installed local project dependencies.",
                "consequences": "Projects using this directory will require running 'npm install' before building.",
                "recommendation": "Only clean if the associated project is archived or inactive.",
                "quarantine_available": True,
            }

        if "npm-cache" in path_lower or "pnpm\\store" in path_lower or "yarn\\cache" in path_lower:
            return {
                "path": str(p),
                "is_dir": is_dir,
                "size": size_bytes,
                "category": ScanCategory.NODE_JS,
                "app_name": "Node.js Package Manager",
                "confidence": "High",
                "safety_tier": "SAFE",
                "explanation": "Global package download cache for npm, pnpm, or yarn.",
                "consequences": "Dependencies will be downloaded from the network when running npm install.",
                "recommendation": "Safe to clean global package caches.",
                "quarantine_available": True,
            }

        # 3. AI Models
        if ".ollama\\models" in path_lower or ".cache\\huggingface\\hub" in path_lower or "comfyui\\models" in path_lower:
            return {
                "path": str(p),
                "is_dir": is_dir,
                "size": size_bytes,
                "category": ScanCategory.AI_MODELS,
                "app_name": "Local AI Tool",
                "confidence": "High",
                "safety_tier": "CAUTION",
                "explanation": "Locally stored AI model weights and tensors.",
                "consequences": "AI models will have to be downloaded again before local inference can run.",
                "recommendation": "Use application CLI (e.g. ollama rm) or review model names before removing.",
                "quarantine_available": True,
            }

        # 4. Logs and crash dumps
        if name_lower.endswith((".log", ".dmp", ".mdmp")) or "crashpad" in parts:
            return {
                "path": str(p),
                "is_dir": is_dir,
                "size": size_bytes,
                "category": ScanCategory.LOGS_CRASH,
                "app_name": cls._detect_owner_app(parts),
                "confidence": "High",
                "safety_tier": "SAFE",
                "explanation": "Historical diagnostic log or application crash dump.",
                "consequences": "Minor. Diagnostic information for software developers will no longer be stored.",
                "recommendation": "Safe to clean if you are not diagnosing a recent crash.",
                "quarantine_available": True,
            }

        # 5. Large files (>500MB)
        if size_bytes >= 500 * 1024 * 1024:
            return {
                "path": str(p),
                "is_dir": is_dir,
                "size": size_bytes,
                "category": ScanCategory.LARGE_FILES,
                "app_name": "Unspecified",
                "confidence": "Medium",
                "safety_tier": "RISKY",
                "explanation": f"Large item consuming {size_bytes / (1024*1024):.1f} MB of disk space.",
                "consequences": "Review to ensure this is not an active video, database, VM disk, or archive.",
                "recommendation": "Manual review recommended.",
                "quarantine_available": True,
            }

        # 6. Browser caches
        if any(b in path_lower for b in ["chrome\\user data\\default\\cache", "msedge\\user data\\default\\cache", "firefox\\profiles", "bravesoftware\\brave-browser\\user data\\default\\cache"]):
            if "cache" in parts or "code cache" in parts or "gpu_cache" in parts:
                return {
                    "path": str(p),
                    "is_dir": is_dir,
                    "size": size_bytes,
                    "category": ScanCategory.BROWSER_CACHE,
                    "app_name": cls._detect_browser_app(path_lower),
                    "confidence": "High",
                    "safety_tier": "SAFE",
                    "explanation": "Temporary cached web images, scripts, and media files.",
                    "consequences": "Web pages may take a fraction of a second longer to load on first visit.",
                    "recommendation": "Safe to clear. Does NOT affect logins, passwords, or bookmarks.",
                    "quarantine_available": True,
                }

        # 7. Temporary files
        if "temp" in parts or "tmp" in parts or name_lower.endswith(".tmp") or name_lower.startswith("~"):
            return {
                "path": str(p),
                "is_dir": is_dir,
                "size": size_bytes,
                "category": ScanCategory.TEMP_FILES,
                "app_name": cls._detect_owner_app(parts),
                "confidence": "High",
                "safety_tier": "SAFE",
                "explanation": "Temporary file or directory left behind by an application process.",
                "consequences": "Negligible. Applications re-create temporary files as needed.",
                "recommendation": "Safe to quarantine and remove.",
                "quarantine_available": True,
            }

        # General application cache fallback
        if "cache" in parts or "caches" in parts:
            return {
                "path": str(p),
                "is_dir": is_dir,
                "size": size_bytes,
                "category": ScanCategory.APP_CACHE,
                "app_name": cls._detect_owner_app(parts),
                "confidence": "Medium",
                "safety_tier": "SAFE",
                "explanation": "Application cache directory.",
                "consequences": "Application will regenerate cached assets automatically.",
                "recommendation": "Safe to quarantine and remove.",
                "quarantine_available": True,
            }

        return cls._fallback_classification(str(p), size_bytes)

    @classmethod
    def _fallback_classification(cls, path_str: str, size_bytes: int) -> Dict[str, Any]:
        return {
            "path": path_str,
            "is_dir": False,
            "size": size_bytes,
            "category": ScanCategory.GENERAL,
            "app_name": "Unknown",
            "confidence": "Low",
            "safety_tier": "CAUTION",
            "explanation": "Unclassified filesystem item.",
            "consequences": "Impact unknown without knowing the parent software.",
            "recommendation": "Manual inspection required.",
            "quarantine_available": True,
        }

    @classmethod
    def _detect_owner_app(cls, parts: list) -> str:
        parts_joined = "/".join(parts).lower()
        if "discord" in parts_joined:
            return "Discord"
        elif "chrome" in parts_joined or "google" in parts_joined:
            return "Chrome"
        elif "edge" in parts_joined or "msedge" in parts_joined:
            return "Edge"
        elif "code" in parts_joined or "vscode" in parts_joined:
            return "VS Code"
        elif "spotify" in parts_joined:
            return "Spotify"
        elif "slack" in parts_joined:
            return "Slack"
        elif "steam" in parts_joined:
            return "Steam"
        elif "pip" in parts_joined or "python" in parts_joined:
            return "Python"
        elif "npm" in parts_joined or "node" in parts_joined:
            return "Node.js"
        elif "ollama" in parts_joined:
            return "Ollama"
        elif "temp" in parts_joined or "windows" in parts_joined or "wer" in parts_joined:
            return "System"
        
        # Common pattern: AppData/Local/<AppVendor>/<AppName>
        for i, part in enumerate(parts):
            if part in ["local", "roaming", "programdata", "localappdata"] and i + 1 < len(parts):
                val = parts[i + 1]
                if val not in ["temp", "packages", "microsoft"]:
                    return val.capitalize()
        return "System"
